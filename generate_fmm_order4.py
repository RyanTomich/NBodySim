"""Emit the private order-4 Laplace translation kernel and contraction as C17."""

from math import comb, prod


def generate():
    # Match the degree, x, y enumeration in laplace.c's laplace_prepare_terms().
    terms = [(x, y, degree - x - y)
             for degree in range(5)
             for x in range(degree + 1)
             for y in range(degree - x + 1)]
    index = {term: i for i, term in enumerate(terms)}
    print("""/* Generated by python3 generate_fmm_order4.py > src/generated/laplace_order4_internal.h */
#ifndef LAPLACE_ORDER4_INTERNAL_H
#define LAPLACE_ORDER4_INTERNAL_H

static inline void laplace_kernel_order4(double kernel[35], const double unit[3])
{
    kernel[0] = 1;""")
    # Expand the same Legendre recurrence and axis order as the generic kernel.
    for i, term in enumerate(terms[1:], 1):
        degree = sum(term)
        linear, quadratic = ["0.0"], ["0.0"]
        for axis, exponent in enumerate(term):
            lower = list(term)
            if exponent:
                lower[axis] -= 1
                linear.append(f"unit[{axis}] * kernel[{index[tuple(lower)]}]")
            if exponent >= 2:
                lower[axis] -= 1
                quadratic.append(f"kernel[{index[tuple(lower)]}]")
        print(f"    kernel[{i}] = -({2 * degree - 1} * ({' + '.join(linear)}) + "
              f"{degree - 1} * ({' + '.join(quadratic)})) / {degree};")
    print("""}

static inline void laplace_contract_order4(double *restrict local, const double *moments,
                                       const double *kernel, const double *source_scale,
                                       const double *target_scale, double r)
{
    double scaled[35];""")
    start = 0
    for degree in range(5):
        # Number of Cartesian monomials of exactly this degree in three axes.
        end = start + comb(degree + 2, 2)
        print(f"    for (int i = {start}; i < {end}; ++i) {{")
        print(f"        scaled[i] = (moments[i] / r) * source_scale[{degree}];")
        print("    }")
        start = end

    # Group by output. Within an output, ascending kernel index reproduces
    # the order of additions in the generic split loop.
    for b, target in enumerate(terms):
        print()
        for a, total in enumerate(terms):
            source = tuple(n - k for n, k in zip(total, target))
            if min(source) < 0:
                continue
            factor = prod(comb(n, k) for n, k in zip(total, target))
            print(f"    local[{b}] += scaled[{index[source]}] * target_scale[{sum(target)}]"
                  f" * {factor} * kernel[{a}];")
    print("}\n\n#endif")


if __name__ == "__main__":
    generate()
